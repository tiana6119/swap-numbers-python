#Activity 3: Swap Numbers

d = 5
e = 10

print("Before swapping:")
print("d =", d)
print("e =", e)

# Swap using a third variable
temp = d
d = d
e = temp

print("After swapping:")
print("d =", d)
print("e =", e)

#Swap without a third variable 

d= 5
e= 10
print("After swapping:")
print("d =", d)
print("e =", e)